// Field names and option lists in each <form data-form> must match what the
// contact function accepts, or real submissions would be rejected.
const formsIn = (html) => [...html.matchAll(/<form[^>]*data-form="([^"]+)"[\s\S]*?<\/form>/g)]
  .map((match) => ({ type: match[1], html: match[0] }));

test("form fields and options match the contact function", () => {
  const common = ["name", "email", "phone", "message", "website"];
  let formCount = 0;
  for (const page of pages) {
    for (const form of formsIn(read(page))) {
      formCount += 1;
      const type = FORM_TYPES[form.type];
      assert.ok(type, `${page}: unknown form type ${form.type}`);
      const allowed = new Set([...common, ...Object.keys(type.fields)]);
      const names = [...form.html.matchAll(/\sname="([^"]+)"/g)].map((match) => match[1]);
      for (const name of names) {
        assert.ok(allowed.has(name), `${page} ${form.type}: field "${name}" is not accepted by the function`);
      }
      assert.ok(names.includes("website"), `${page} ${form.type}: honeypot missing`);
      assert.match(form.html, /data-form-status/, `${page} ${form.type}: status region missing`);

      for (const [field, rule] of Object.entries(type.fields)) {
        const allowedValues = rule.oneOf || rule.list;
        if (!allowedValues) {
          continue;
        }
        if (rule.list) {
          const values = [...form.html.matchAll(new RegExp(`name="${field.replace(/[[\]]/g, "\\$&")}" value="([^"]+)"`, "g"))]
            .map((match) => match[1].replace(/&amp;/g, "&"));
          for (const value of values) {
            assert.ok(allowedValues.has(value), `${page} ${field}: "${value}" not accepted`);
          }
          continue;
        }
        const select = form.html.match(new RegExp(`<select[^>]*name="${field}"[\\s\\S]*?<\\/select>`));
        if (!select) {
          continue;
        }
        const options = [...select[0].matchAll(/<option(?: value="([^"]*)")?>([^<]*)<\/option>/g)]
          .map((match) => (match[1] !== undefined ? match[1] : match[2]).replace(/&amp;/g, "&"))
          .filter(Boolean);
        for (const option of options) {
          assert.ok(allowedValues.has(option), `${page} ${field}: option "${option}" not accepted`);
        }
      }
    }
  }
  assert.ok(formCount >= 5, "expected forms on About, Contact, Events, Partners and Careers");
});

