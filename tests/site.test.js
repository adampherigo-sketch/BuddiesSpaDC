const localRefs = (html) => [...html.matchAll(/\s(?:href|src)="([^"]+)"/g)]
  .map((match) => match[1])
  .filter((url) => !/^(https?:|mailto:|tel:|#|data:)/.test(url))
  .map((url) => url.split("#")[0].split("?")[0])
  .filter(Boolean);

test("every page exists and has the shared shell", () => {
  for (const page of pages) {
    assert.ok(exists(page), `${page} is missing`);
    const html = read(page);
    assert.match(html, /<html lang="en">/, `${page} lang`);
    assert.match(html, /<title>[^<]{10,}<\/title>/, `${page} title`);
    assert.match(html, /<meta name="description" content="[^"]{40,}">/, `${page} description`);
    assert.match(html, /<header class="site-header" data-site-header><\/header>/, `${page} header slot`);
    assert.match(html, /<footer class="site-footer" data-site-footer><\/footer>/, `${page} footer slot`);
    assert.match(html, /<main id="main">/, `${page} main landmark`);
    assert.match(html, /class="skip-link" href="#main"/, `${page} skip link`);
    assert.match(html, /property="og:image"/, `${page} og:image`);
    assert.match(html, /rel="icon"/, `${page} favicon`);
    const order = ["js/site-config.js", "js/feeds.js", "js/nav.js"].map((src) => html.indexOf(`src="${src}"`));
    assert.ok(order.every((index) => index > 0) && order[0] < order[1] && order[1] < order[2], `${page} loads config, feeds, nav in order`);
    assert.equal((html.match(/<h1[\s>]/g) || []).length, 1, `${page} has exactly one h1`);
  }
});

