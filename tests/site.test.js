test("home page specials spotlight is wired up correctly", () => {
  const html = read("index.html");
  const section = html.match(/<section class="bs-spotlight"[\s\S]*?<\/section>/);
  assert.ok(section, "spotlight section missing");
  const markup = section[0];
  assert.match(markup, /id="specials"/);
  assert.match(markup, /aria-labelledby="specials-title"/);
  assert.match(markup, /<h2[^>]*id="specials-title"/);
  const expires = markup.match(/data-expires="([^"]+)"/)[1];
  assert.match(expires, /^\d{4}-\d{2}-\d{2}$/, "data-expires must be YYYY-MM-DD");
  const tabs = [...markup.matchAll(/role="tab" id="([^"]+)" aria-selected="(true|false)" aria-controls="([^"]+)" tabindex="(0|-1)" data-key="([^"]+)"/g)];
  assert.equal(tabs.length, 4, "four tabs");
  assert.equal(tabs.filter((t) => t[2] === "true").length, 1, "exactly one tab selected");
  for (const [, tabId, selected, panelId, tabindex, key] of tabs) {
    assert.equal(tabindex, selected === "true" ? "0" : "-1", `${tabId} roving tabindex`);
    assert.equal(panelId, `special-${key}`, `${tabId} controls special-${key}`);
    assert.match(markup, new RegExp(`role="tabpanel" id="${panelId}" aria-labelledby="${tabId}"`), `${panelId} labelled by ${tabId}`);
  }
  const defaultKey = markup.match(/data-default="([^"]+)"/)[1];
  assert.ok(tabs.some((t) => t[5] === defaultKey), "data-default matches a tab");
  assert.equal((markup.match(/<h3 class="bs-spotlight__label">/g) || []).length, 4, "panel department labels are h3");
  assert.ok([...markup.matchAll(/<img [^>]*alt="([^"]*)"/g)].every((m) => m[1].length > 10), "every photo has real alt text");
});

