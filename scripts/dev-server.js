// Buddies Spa — local preview with live reload. No dependencies.
//
//   npm run dev                          → http://localhost:5503 (opens your browser)
//   http://localhost:5503/?intro         → the welcome doors replay on every load
//
// Serves the source files directly (no build step needed). Saving a page,
// script, data file or image reloads the browser; saving CSS swaps the
// stylesheets in place without a reload, so you can tweak styles while the
// intro is half open.
//
// It sends the live site's security headers (minus the HTTPS-only and
// no-framing rules, which don't apply on localhost), so anything the live
// site would block is blocked here too. Forms are checked by the real contact
// function's validation but never emailed; Google reviews show labeled samples.

const http = require("node:http");
const fs = require("node:fs");
const path = require("node:path");
const { execFile } = require("node:child_process");

const ROOT = path.resolve(__dirname, "..");
const DEFAULT_PORT = 5503;
const LIVE_SCRIPT = "/__dev/live.js";
const EVENTS_PATH = "/__dev/events";
const MAX_BODY_BYTES = 32 * 1024;

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".svg": "image/svg+xml",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8"
};

// Only what the live site publishes, plus partials/ (the build inlines them).
const PUBLIC_DIRS = new Set(["css", "js", "fonts", "data", "images", "partials"]);

// Runs in the browser: reload on page/script changes, swap CSS in place.
const LIVE_CLIENT = `(() => {
  const events = new EventSource(${JSON.stringify(EVENTS_PATH)});
  let connected = false;
  events.addEventListener("open", () => {
    if (connected) {
      window.location.reload(); // the dev server restarted
    }
    connected = true;
  });
  events.addEventListener("reload", () => window.location.reload());
  events.addEventListener("css", () => {
    document.querySelectorAll('link[rel="stylesheet"]').forEach((link) => {
      const url = new URL(link.href);
      url.searchParams.set("v", Date.now());
      link.href = url.href;
    });
  });
})();
`;

const SAMPLE_REVIEWS = {
  ok: true,
  dev: true,
  rating: 5,
  userRatingCount: 3,
  googleMapsUri: "",
  reviews: [1, 2, 3].map((n) => ({
    author: `Sample reviewer ${n}`,
    authorUri: "",
    rating: 5,
    text: "Sample review shown only in the local preview, so you can see and style this section. Real Google reviews replace it after deploy.",
    relativeTime: "local preview",
    publishTime: ""
  }))
};

// The live site's headers from _headers ("/*" block), adjusted for localhost.
const devHeaders = (root = ROOT) => {
  const headers = {};
  let text = "";
  try {
    text = fs.readFileSync(path.join(root, "_headers"), "utf8");
  } catch {
    return headers;
  }
  const block = text.split(/\n(?=\S)/).find((section) => section.startsWith("/*\n")) || "";
  for (const line of block.split("\n").slice(1)) {
    const match = line.match(/^\s+([\w-]+):\s*(.+)$/);
    if (match) {
      headers[match[1]] = match[2].trim();
    }
  }
  delete headers["Strict-Transport-Security"]; // never pin localhost to HTTPS
  delete headers["X-Frame-Options"]; // allow VS Code's Simple Browser
  if (headers["Content-Security-Policy"]) {
    headers["Content-Security-Policy"] = headers["Content-Security-Policy"]
      .split(";")
      .map((directive) => directive.trim())
      .filter((directive) => directive && !/^(upgrade-insecure-requests|frame-ancestors)\b/.test(directive))
      .join("; ");
  }
  return headers;
};

// URL path → file inside the project, or null if it isn't public.
const resolveFile = (urlPath, root = ROOT) => {
  let pathname;
  try {
    pathname = decodeURIComponent(urlPath.split("?")[0].split("#")[0]);
  } catch {
    return null;
  }
  if (pathname === "/") {
    pathname = "/index.html";
  }
  const segments = pathname.split("/").filter(Boolean);
  if (!segments.length || segments.some((segment) => segment.startsWith(".") || segment.includes("\\"))) {
    return null;
  }
  if (segments.length === 1) {
    // Pages live at the root; /services works like /services.html (as on Netlify).
    const name = path.extname(segments[0]) ? segments[0] : `${segments[0]}.html`;
    if (!name.endsWith(".html")) {
      return null;
    }
    segments[0] = name;
  } else if (!PUBLIC_DIRS.has(segments[0])) {
    return null;
  }
  const candidates = [path.join(root, ...segments)];
  // Favicons and the share image are generated by the build.
  if (segments[0] === "images" && segments[1] === "brand") {
    candidates.push(path.join(root, "dist", ...segments));
  }
  for (const file of candidates) {
    if (file.startsWith(root + path.sep) && fs.existsSync(file) && fs.statSync(file).isFile()) {
      return file;
    }
  }
  return null;
};

const readBody = (request) => new Promise((resolve, reject) => {
  let size = 0;
  const chunks = [];
  request.on("data", (chunk) => {
    size += chunk.length;
    if (size > MAX_BODY_BYTES) {
      reject(new Error("too large"));
      request.destroy();
      return;
    }
    chunks.push(chunk);
  });
  request.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
  request.on("error", reject);
});

const createDevServer = ({ root = ROOT, log = () => {} } = {}) => {
  const headers = devHeaders(root);
  const clients = new Set();
  const { validateRequest } = require(path.join(root, "netlify/functions/contact.js"));

  const send = (response, status, body, type, extra = {}) => {
    response.writeHead(status, { ...headers, "Cache-Control": "no-store", "Content-Type": type, ...extra });
    response.end(body);
  };
  const sendJson = (response, status, payload) => send(response, status, JSON.stringify(payload), TYPES[".json"]);

  const handleContact = async (request, response) => {
    let body;
    try {
      body = JSON.parse(await readBody(request));
    } catch {
      sendJson(response, 400, { ok: false, error: "invalid_json" });
      return;
    }
    if (body && typeof body.website === "string" && body.website.trim()) {
      sendJson(response, 200, { ok: true });
      return;
    }
    const submission = validateRequest(body);
    if (!submission) {
      log("Form rejected by validation (same rules as the live site).");
      sendJson(response, 400, { ok: false, error: "validation_error" });
      return;
    }
    log(`Form "${submission.form_type}" from ${submission.page} passed validation (local preview: not emailed).`);
    sendJson(response, 200, { ok: true, dev: true });
  };

  const server = http.createServer(async (request, response) => {
    const url = new URL(request.url, "http://localhost");

    if (url.pathname === EVENTS_PATH) {
      response.writeHead(200, { "Content-Type": "text/event-stream", "Cache-Control": "no-store", Connection: "keep-alive" });
      response.write(": connected\n\n");
      clients.add(response);
      request.on("close", () => clients.delete(response));
      return;
    }
    if (url.pathname === LIVE_SCRIPT) {
      send(response, 200, LIVE_CLIENT, TYPES[".js"]);
      return;
    }
    if (url.pathname === "/.netlify/functions/reviews") {
      sendJson(response, 200, SAMPLE_REVIEWS);
      return;
    }
    if (url.pathname === "/.netlify/functions/contact") {
      if (request.method !== "POST") {
        sendJson(response, 405, { ok: false, error: "method_not_allowed" });
        return;
      }
      await handleContact(request, response);
      return;
    }
    if (request.method !== "GET" && request.method !== "HEAD") {
      send(response, 405, "Method not allowed", TYPES[".txt"]);
      return;
    }

    const file = resolveFile(url.pathname, root);
    const status = file ? 200 : 404;
    const target = file || path.join(root, "404.html");
    const extension = path.extname(target).toLowerCase();
    let body = fs.readFileSync(target);
    if (extension === ".html") {
      body = body.toString("utf8").replace("</head>", `  <script src="${LIVE_SCRIPT}" defer></script>\n</head>`);
    }
    send(response, status, request.method === "HEAD" ? undefined : body, TYPES[extension] || "application/octet-stream");
  });

  // Tell every open page to reload ("reload") or swap stylesheets ("css").
  const notify = (kind) => {
    for (const client of clients) {
      client.write(`event: ${kind}\ndata: ${Date.now()}\n\n`);
    }
  };

  // Keep idle connections open through proxies and sleep.
  const keepAlive = setInterval(() => {
    for (const client of clients) {
      client.write(": ping\n\n");
    }
  }, 25000);
  keepAlive.unref();
  server.on("close", () => {
    clearInterval(keepAlive);
    for (const client of clients) {
      client.end();
    }
  });

  return { server, notify };
};

// Watch the source and push changes to open pages (debounced: editors
// often write a file more than once per save).
const WATCHED = new Set([".html", ".css", ".js", ".json", ".png", ".jpg", ".jpeg", ".webp", ".svg", ".woff2"]);
const IGNORED = /^(node_modules|dist|tests|scripts|netlify|brand-source|docs)(\/|$)|(^|\/)\./;

const watchSource = (root, notify, log) => {
  let timer = null;
  const changed = new Set();
  fs.watch(root, { recursive: true }, (eventType, filename) => {
    if (!filename) {
      return;
    }
    const relative = filename.split(path.sep).join("/");
    if (IGNORED.test(relative) || !WATCHED.has(path.extname(relative).toLowerCase())) {
      return;
    }
    changed.add(relative);
    clearTimeout(timer);
    timer = setTimeout(() => {
      const onlyCss = [...changed].every((file) => file.endsWith(".css"));
      log(`${onlyCss ? "Styles updated" : "Reloaded"}: ${[...changed].join(", ")}`);
      notify(onlyCss ? "css" : "reload");
      changed.clear();
    }, 250);
  });
};

const openBrowser = (url) => {
  const [command, args] = process.platform === "darwin"
    ? ["open", [url]]
    : process.platform === "win32"
      ? ["cmd", ["/c", "start", "", url]]
      : ["xdg-open", [url]];
  execFile(command, args, () => {});
};

const main = () => {
  const log = (message) => console.log(`[dev] ${message}`);
  const { server, notify } = createDevServer({ log });
  const wantsOpen = process.argv.includes("--open");
  let port = Number(process.env.PORT) || DEFAULT_PORT;

  server.on("error", (error) => {
    if (error.code === "EADDRINUSE" && port < DEFAULT_PORT + 20) {
      port += 1; // e.g. VS Code Live Server already on 5503
      server.listen(port, "127.0.0.1");
      return;
    }
    throw error;
  });

  server.on("listening", () => {
    const base = `http://localhost:${port}`;
    console.log(`\nBuddies Spa preview running:\n`);
    console.log(`  ${base}/            the site (live reload on save)`);
    console.log(`  ${base}/?intro      replays the welcome doors on every load`);
    console.log(`\nForms are validated but not emailed; reviews are samples. Ctrl+C to stop.\n`);
    watchSource(ROOT, notify, log);
    if (wantsOpen) {
      openBrowser(`${base}/?intro`);
    }
  });

  server.listen(port, "127.0.0.1");
};

if (require.main === module) {
  main();
}

module.exports = { createDevServer, resolveFile, devHeaders, LIVE_SCRIPT };
